// @ts-nocheck
// Чужой текст перед вставкой в терминал (t75). Текст с сайта может нести невидимые управляющие знаки.
// ESC[201~ закрывает скобки вставки, и перевод строки после них программа примет за Enter — команда исполнится сама.
// Орка заменяет ESC на видимый ␛ (terminal-pty-input-transaction-*.js, функция u) — так же и здесь: видно, что знак был.
// Остальные управляющие C0 (кроме табуляции и перевода строки), DEL и C1 0x80–0x9F убираются: вне скобок ^C прервал бы
// программу, ^H стёр бы набранное, 0x9B — это CSI одним знаком. В обычном тексте их не бывает. Орка их не трогает.
// Переводы строки — все к LF: одиночный CR xterm не меняет, и он ушёл бы в программу как Enter.
// Ту же очистку возьмёт вставка текста со страницы встроенного браузера (t39) — через pasteText терминала вкладки.

/**
 * @param {string} text
 * @returns {string} текст без управляющих знаков, кроме табуляции и LF; ESC — видимым ␛
 */
function cleanPasteText(text) {
  return String(text)
    .replace(/\r\n?/g, '\n')
    .replace(/\x1b/g, '␛')
    .replace(/[\x00-\x08\x0B-\x1F\x7F-\x9F]/g, '');
}

if (typeof module !== 'undefined') module.exports = { cleanPasteText };
